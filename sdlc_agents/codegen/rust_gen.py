"""Rust code generator — Cargo project with built-in ``cargo test`` unit tests."""

from __future__ import annotations

from typing import List

from ..analysis import ProjectSpec
from ..languages import TestFramework
from ..types import Artifact
from .base import CodeGenerator, core_class, operation_idents, pkg_name


class RustGenerator(CodeGenerator):
    language_id = "rust"

    def _ops(self, spec: ProjectSpec) -> List[str]:
        return operation_idents(spec)

    def source_files(self, spec: ProjectSpec) -> List[Artifact]:
        cls = core_class(spec)
        ops = self._ops(spec)
        op_methods = "\n".join(
            f'''
    /// Operation `{op}` derived from the requirements.
    pub fn {op}(&mut self, name: &str) -> bool {{
        if !self.validate(name).is_empty() {{
            return false;
        }}
        self.record("{op}");
        true
    }}'''
            for op in ops
        )
        lib = f'''//! Core library for {spec.title}.
//!
//! Auto-generated by the SDLC Agents Software Developer agent. Deterministic,
//! dependency-light and fully offline. Unit tests use Rust's built-in test
//! harness (`cargo test`).

/// Business logic for {spec.title}.
#[derive(Debug, Default)]
pub struct {cls} {{
    audit: Vec<String>,
}}

impl {cls} {{
    /// Create a new, empty service.
    pub fn new() -> Self {{
        {cls} {{ audit: Vec::new() }}
    }}

    /// Validate an input name, returning a list of error messages (empty = ok).
    pub fn validate(&self, name: &str) -> Vec<String> {{
        let mut errors = Vec::new();
        if name.trim().is_empty() {{
            errors.push("name must not be empty".to_string());
        }}
        errors
    }}

    /// Record an operation in the in-memory audit log.
    pub fn record(&mut self, operation: &str) {{
        self.audit.push(operation.to_string());
    }}

    /// Main pipeline: validate then record a `process` operation.
    pub fn process(&mut self, name: &str) -> bool {{
        if !self.validate(name).is_empty() {{
            return false;
        }}
        self.record("process");
        true
    }}
{op_methods}

    /// Number of recorded operations.
    pub fn count(&self) -> usize {{
        self.audit.len()
    }}
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn validate_rejects_empty() {{
        assert!(!{cls}::new().validate("  ").is_empty());
    }}

    #[test]
    fn validate_accepts_non_empty() {{
        assert!({cls}::new().validate("order-1").is_empty());
    }}

    #[test]
    fn process_increments_count() {{
        let mut svc = {cls}::new();
        assert!(svc.process("order-1"));
        assert_eq!(svc.count(), 1);
    }}

    #[test]
    fn process_rejects_invalid() {{
        let mut svc = {cls}::new();
        assert!(!svc.process(""));
        assert_eq!(svc.count(), 0);
    }}
}}
'''
        return [Artifact(path="src/lib.rs", content=lib, kind="code", language="rust")]

    def unit_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        # Rust unit tests live inline in src/lib.rs (idiomatic); nothing extra.
        return []

    def integration_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        cls = core_class(spec)
        crate = pkg_name(spec)
        content = f'''//! Integration tests for {spec.title} (auto-generated).
//! Exercises the public API end-to-end via `cargo test`.

use {crate}::{cls};

#[test]
fn end_to_end_flow() {{
    let mut svc = {cls}::new();
    for i in 0..3 {{
        assert!(svc.process(&format!("rec-{{}}", i)));
    }}
    assert_eq!(svc.count(), 3);
}}

#[test]
fn invalid_then_valid_flow() {{
    let mut svc = {cls}::new();
    assert!(!svc.process(""));
    assert!(svc.process("ok-1"));
    assert_eq!(svc.count(), 1);
}}
'''
        return [Artifact(path="tests/integration.rs", content=content, kind="test", language="rust")]

    def build_manifest(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        crate = pkg_name(spec)
        content = f'''[package]
name = "{crate}"
version = "0.1.0"
edition = "2021"
description = "{spec.title} — generated by SDLC Agents."

[lib]
name = "{crate}"
path = "src/lib.rs"

[dependencies]
'''
        return [Artifact(path="Cargo.toml", content=content, kind="code", language="toml")]

    def component_design(self, spec: ProjectSpec, framework: TestFramework) -> str:
        cls = core_class(spec)
        crate = pkg_name(spec)
        ops = ", ".join(f"`{o}`" for o in self._ops(spec))
        return f'''# Component Design
## {spec.title}

*Target language: **Rust** · unit tests: **{framework.display}**.*

## Crate Layout
```
Cargo.toml
src/lib.rs          # {cls} core logic + #[cfg(test)] unit tests
tests/integration.rs # end-to-end integration tests
```

## Public Interface: `{cls}`
- `new() -> {cls}` — construct an empty service.
- `validate(name: &str) -> Vec<String>` — validation errors (empty = valid).
- `process(name: &str) -> bool` — validate then record a `process` operation.
- `record(operation: &str)` — append to the audit log.
- `count() -> usize` — number of recorded operations.
- Domain operations: {ops}.

## Build & Test
```
cargo build
cargo test        # runs inline unit tests + tests/integration.rs
```

Use `{crate}` as the crate name when importing from integration tests.
'''
