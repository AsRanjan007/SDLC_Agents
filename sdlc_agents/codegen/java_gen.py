"""Java code generator — Maven project with JUnit 5 / JUnit 4 / TestNG tests."""

from __future__ import annotations

from typing import List

from ..analysis import ProjectSpec
from ..languages import TestFramework
from ..types import Artifact
from .base import CodeGenerator, camel, core_class, operation_idents, pkg_name

_GROUP = "com.sdlcagents"


class JavaGenerator(CodeGenerator):
    language_id = "java"

    def _pkg(self, spec: ProjectSpec) -> str:
        return f"{_GROUP}.{pkg_name(spec)}"

    def _pkg_path(self, spec: ProjectSpec) -> str:
        return self._pkg(spec).replace(".", "/")

    def _ops(self, spec: ProjectSpec) -> List[str]:
        return [camel(o) for o in operation_idents(spec)]

    def source_files(self, spec: ProjectSpec) -> List[Artifact]:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        ops = self._ops(spec)
        op_methods = "\n".join(
            f'''
    /** Operation '{op}' derived from the requirements. */
    public boolean {op}(String name) {{
        if (!validate(name).isEmpty()) {{
            return false;
        }}
        record("{op}");
        return true;
    }}'''
            for op in ops
        )
        src = f'''package {pkg};

import java.util.ArrayList;
import java.util.List;

/**
 * Business logic for {spec.title}.
 *
 * Auto-generated by the SDLC Agents Software Developer agent. Deterministic,
 * dependency-light and fully offline.
 */
public class {cls} {{

    private final List<String> audit = new ArrayList<>();

    /** Validate an input name; returns error messages (empty = valid). */
    public List<String> validate(String name) {{
        List<String> errors = new ArrayList<>();
        if (name == null || name.trim().isEmpty()) {{
            errors.add("name must not be empty");
        }}
        return errors;
    }}

    /** Record an operation in the in-memory audit log. */
    public void record(String operation) {{
        audit.add(operation);
    }}

    /** Main pipeline: validate then record a 'process' operation. */
    public boolean process(String name) {{
        if (!validate(name).isEmpty()) {{
            return false;
        }}
        record("process");
        return true;
    }}
{op_methods}

    /** Number of recorded operations. */
    public int count() {{
        return audit.size();
    }}
}}
'''
        return [Artifact(path=f"src/main/java/{self._pkg_path(spec)}/{cls}.java", content=src, kind="code", language="java")]

    def unit_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        first = self._ops(spec)[0]
        if framework.id == "junit4":
            imports = "import org.junit.Test;\nimport static org.junit.Assert.*;"
            annotation = "@Test"
        elif framework.id == "testng":
            imports = "import org.testng.annotations.Test;\nimport static org.testng.Assert.*;"
            annotation = "@Test"
        else:  # junit5
            imports = (
                "import org.junit.jupiter.api.Test;\n"
                "import static org.junit.jupiter.api.Assertions.*;"
            )
            annotation = "@Test"
        src = f'''package {pkg};

{imports}

public class {cls}Test {{

    {annotation}
    public void validateRejectsEmpty() {{
        assertFalse(new {cls}().validate("  ").isEmpty());
    }}

    {annotation}
    public void validateAcceptsNonEmpty() {{
        assertTrue(new {cls}().validate("order-1").isEmpty());
    }}

    {annotation}
    public void processIncrementsCount() {{
        {cls} svc = new {cls}();
        assertTrue(svc.process("order-1"));
        assertEquals(1, svc.count());
    }}

    {annotation}
    public void processRejectsInvalid() {{
        {cls} svc = new {cls}();
        assertFalse(svc.process(""));
        assertEquals(0, svc.count());
    }}

    {annotation}
    public void operationIncrementsCount() {{
        {cls} svc = new {cls}();
        assertTrue(svc.{first}("order-1"));
        assertEquals(1, svc.count());
    }}
}}
'''
        return [Artifact(path=f"src/test/java/{self._pkg_path(spec)}/{cls}Test.java", content=src, kind="test", language="java")]

    def integration_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        if framework.id == "junit4":
            imports = "import org.junit.Test;\nimport static org.junit.Assert.*;"
        elif framework.id == "testng":
            imports = "import org.testng.annotations.Test;\nimport static org.testng.Assert.*;"
        else:
            imports = (
                "import org.junit.jupiter.api.Test;\n"
                "import static org.junit.jupiter.api.Assertions.*;"
            )
        src = f'''package {pkg};

{imports}

public class {cls}IT {{

    @Test
    public void endToEndFlow() {{
        {cls} svc = new {cls}();
        for (int i = 0; i < 3; i++) {{
            assertTrue(svc.process("rec-" + i));
        }}
        assertEquals(3, svc.count());
    }}

    @Test
    public void invalidThenValidFlow() {{
        {cls} svc = new {cls}();
        assertFalse(svc.process(""));
        assertTrue(svc.process("ok-1"));
        assertEquals(1, svc.count());
    }}
}}
'''
        return [Artifact(path=f"src/test/java/{self._pkg_path(spec)}/{cls}IT.java", content=src, kind="test", language="java")]

    def build_manifest(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        artifact_id = pkg_name(spec).replace("_", "-")
        if framework.id == "junit4":
            deps = '''    <dependency>
      <groupId>junit</groupId>
      <artifactId>junit</artifactId>
      <version>4.13.2</version>
      <scope>test</scope>
    </dependency>'''
        elif framework.id == "testng":
            deps = '''    <dependency>
      <groupId>org.testng</groupId>
      <artifactId>testng</artifactId>
      <version>7.10.2</version>
      <scope>test</scope>
    </dependency>'''
        else:  # junit5
            deps = '''    <dependency>
      <groupId>org.junit.jupiter</groupId>
      <artifactId>junit-jupiter</artifactId>
      <version>5.10.2</version>
      <scope>test</scope>
    </dependency>'''
        pom = f'''<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <groupId>{_GROUP}</groupId>
  <artifactId>{artifact_id}</artifactId>
  <version>0.1.0</version>
  <packaging>jar</packaging>
  <name>{spec.title}</name>
  <description>Generated by SDLC Agents.</description>

  <properties>
    <maven.compiler.release>17</maven.compiler.release>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
  </properties>

  <dependencies>
{deps}
  </dependencies>

  <build>
    <plugins>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-surefire-plugin</artifactId>
        <version>3.2.5</version>
      </plugin>
    </plugins>
  </build>
</project>
'''
        return [Artifact(path="pom.xml", content=pom, kind="code", language="xml")]

    def component_design(self, spec: ProjectSpec, framework: TestFramework) -> str:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        ops = ", ".join(f"`{o}`" for o in self._ops(spec))
        return f'''# Component Design
## {spec.title}

*Target language: **Java** · unit tests: **{framework.display}**.*

## Maven Layout
```
pom.xml
src/main/java/{self._pkg_path(spec)}/{cls}.java
src/test/java/{self._pkg_path(spec)}/{cls}Test.java   # unit tests
src/test/java/{self._pkg_path(spec)}/{cls}IT.java     # integration tests
```

## Public Interface: `{pkg}.{cls}`
- `List<String> validate(String name)` — validation errors (empty = valid).
- `boolean process(String name)` — validate then record a `process` operation.
- `void record(String operation)` — append to the audit log.
- `int count()` — number of recorded operations.
- Domain operations: {ops}.

## Build & Test
```
mvn test
```
'''
