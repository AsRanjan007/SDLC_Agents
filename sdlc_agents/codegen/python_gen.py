"""Python code generator.

Reuses the battle-tested deterministic templates in :mod:`offline_engine` for the
pytest flow, and adds a ``unittest`` variant so the user's framework choice is
honoured precisely.
"""

from __future__ import annotations

from typing import List

from ..analysis import ProjectSpec
from ..languages import TestFramework
from ..llm import offline_engine
from ..types import Artifact
from .base import CodeGenerator, core_class, operation_idents, pkg_name


class PythonGenerator(CodeGenerator):
    language_id = "python"

    def source_files(self, spec: ProjectSpec) -> List[Artifact]:
        return offline_engine.render_source_files(spec)

    def unit_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        if framework.id == "unittest":
            return [_unittest_module(spec)]
        return offline_engine.render_unit_tests(spec)

    def integration_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        if framework.id == "unittest":
            return [_unittest_integration(spec)]
        return offline_engine.render_integration_tests(spec)

    def build_manifest(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        pkg = pkg_name(spec)
        content = (
            "[build-system]\n"
            'requires = ["setuptools>=61"]\n'
            'build-backend = "setuptools.build_meta"\n\n'
            "[project]\n"
            f'name = "{pkg}"\n'
            'version = "0.1.0"\n'
            f'description = "{spec.title} — generated by SDLC Agents."\n'
            'requires-python = ">=3.9"\n\n'
            "[tool.pytest.ini_options]\n"
            'pythonpath = ["src"]\n'
            'testpaths = ["tests"]\n'
        )
        return [Artifact(path="pyproject.toml", content=content, kind="code", language="toml")]

    def component_design(self, spec: ProjectSpec, framework: TestFramework) -> str:
        body = offline_engine.render_component_design(spec)
        header = f"*Target language: **Python** · unit tests: **{framework.display}**.*\n\n"
        footer = (
            "\n## Build & Test\n```\n"
            "pip install pytest\n"
            + ("pytest\n" if framework.id == "pytest" else "python -m unittest discover\n")
            + "```\n"
        )
        # Insert the language header just after the top-level title line.
        lines = body.splitlines(keepends=True)
        if len(lines) >= 2:
            body = "".join(lines[:2]) + "\n" + header + "".join(lines[2:])
        else:
            body = header + body
        return body + footer


def _unittest_module(spec: ProjectSpec) -> Artifact:
    cls = core_class(spec)
    pkg = pkg_name(spec)
    ops = operation_idents(spec)
    first = ops[0]
    content = f'''"""Unit tests for {spec.title} (auto-generated, unittest)."""

import unittest

from {pkg}.core import {cls}


class {cls}Test(unittest.TestCase):
    def test_validate_input_missing_fields(self):
        errors = {cls}().validate_input({{}})
        self.assertIn("missing required field: id", errors)
        self.assertIn("missing required field: payload", errors)

    def test_validate_input_accepts_valid(self):
        self.assertEqual({cls}().validate_input({{"id": 1, "payload": {{}}}}), [])

    def test_process_success(self):
        result = {cls}().process({{"id": "r1", "payload": {{"x": 1}}}})
        self.assertTrue(result.ok)
        self.assertIsNotNone(result.record)

    def test_process_rejects_invalid(self):
        result = {cls}().process({{}})
        self.assertFalse(result.ok)
        self.assertTrue(result.errors)

    def test_operation_records_audit(self):
        svc = {cls}()
        svc.{first}({{"k": "v"}})
        self.assertEqual(svc.audit_log[-1]["operation"], "{first}")


if __name__ == "__main__":
    unittest.main()
'''
    return Artifact(path="tests/unit/test_core.py", content=content, kind="test", language="python")


def _unittest_integration(spec: ProjectSpec) -> Artifact:
    cls = core_class(spec)
    pkg = pkg_name(spec)
    content = f'''"""Integration tests for {spec.title} (auto-generated, unittest)."""

import unittest

from {pkg}.core import {cls}


class {cls}IntegrationTest(unittest.TestCase):
    def test_end_to_end_flow(self):
        svc = {cls}()
        for i in range(3):
            self.assertTrue(svc.process({{"id": f"rec-{{i}}", "payload": {{"value": i}}}}).ok)
        report = svc.report()
        self.assertGreaterEqual(report["total_operations"], 3)
        self.assertIn("process", report["by_operation"])


if __name__ == "__main__":
    unittest.main()
'''
    return Artifact(path="tests/integration/test_integration.py", content=content, kind="test", language="python")
