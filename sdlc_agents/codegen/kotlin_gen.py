"""Kotlin code generator — Gradle project with Kotest (default) or JUnit 5."""

from __future__ import annotations

from typing import List

from ..analysis import ProjectSpec
from ..languages import TestFramework
from ..types import Artifact
from .base import CodeGenerator, camel, core_class, operation_idents, pkg_name

_GROUP = "com.sdlcagents"


class KotlinGenerator(CodeGenerator):
    language_id = "kotlin"

    def _pkg(self, spec: ProjectSpec) -> str:
        return f"{_GROUP}.{pkg_name(spec)}"

    def _pkg_path(self, spec: ProjectSpec) -> str:
        return self._pkg(spec).replace(".", "/")

    def _ops(self, spec: ProjectSpec) -> List[str]:
        return [camel(o) for o in operation_idents(spec)]

    def source_files(self, spec: ProjectSpec) -> List[Artifact]:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        ops = self._ops(spec)
        op_methods = "\n".join(
            f'''
    /** Operation '{op}' derived from the requirements. */
    fun {op}(name: String): Boolean {{
        if (validate(name).isNotEmpty()) return false
        record("{op}")
        return true
    }}'''
            for op in ops
        )
        src = f'''package {pkg}

/**
 * Business logic for {spec.title}.
 *
 * Auto-generated by the SDLC Agents Software Developer agent. Deterministic,
 * dependency-light and fully offline.
 */
class {cls} {{

    private val audit = mutableListOf<String>()

    /** Validate an input name; returns error messages (empty = valid). */
    fun validate(name: String): List<String> {{
        val errors = mutableListOf<String>()
        if (name.isBlank()) errors.add("name must not be empty")
        return errors
    }}

    /** Record an operation in the in-memory audit log. */
    fun record(operation: String) {{
        audit.add(operation)
    }}

    /** Main pipeline: validate then record a 'process' operation. */
    fun process(name: String): Boolean {{
        if (validate(name).isNotEmpty()) return false
        record("process")
        return true
    }}
{op_methods}

    /** Number of recorded operations. */
    fun count(): Int = audit.size
}}
'''
        return [Artifact(path=f"src/main/kotlin/{self._pkg_path(spec)}/{cls}.kt", content=src, kind="code", language="kotlin")]

    def unit_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        first = self._ops(spec)[0]
        if framework.id == "junit5":
            src = f'''package {pkg}

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.Assertions.*

class {cls}Test {{

    @Test
    fun validateRejectsEmpty() {{
        assertTrue({cls}().validate("  ").isNotEmpty())
    }}

    @Test
    fun validateAcceptsNonEmpty() {{
        assertTrue({cls}().validate("order-1").isEmpty())
    }}

    @Test
    fun processIncrementsCount() {{
        val svc = {cls}()
        assertTrue(svc.process("order-1"))
        assertEquals(1, svc.count())
    }}

    @Test
    fun processRejectsInvalid() {{
        val svc = {cls}()
        assertFalse(svc.process(""))
        assertEquals(0, svc.count())
    }}

    @Test
    fun operationIncrementsCount() {{
        val svc = {cls}()
        assertTrue(svc.{first}("order-1"))
        assertEquals(1, svc.count())
    }}
}}
'''
        else:  # kotest
            src = f'''package {pkg}

import io.kotest.core.spec.style.StringSpec
import io.kotest.matchers.shouldBe

class {cls}Test : StringSpec({{

    "validate rejects empty input" {{
        {cls}().validate("  ").isNotEmpty() shouldBe true
    }}

    "validate accepts non-empty input" {{
        {cls}().validate("order-1").isEmpty() shouldBe true
    }}

    "process increments the operation count" {{
        val svc = {cls}()
        svc.process("order-1") shouldBe true
        svc.count() shouldBe 1
    }}

    "process rejects invalid input" {{
        val svc = {cls}()
        svc.process("") shouldBe false
        svc.count() shouldBe 0
    }}

    "domain operation increments the count" {{
        val svc = {cls}()
        svc.{first}("order-1") shouldBe true
        svc.count() shouldBe 1
    }}
}})
'''
        return [Artifact(path=f"src/test/kotlin/{self._pkg_path(spec)}/{cls}Test.kt", content=src, kind="test", language="kotlin")]

    def integration_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        if framework.id == "junit5":
            src = f'''package {pkg}

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.Assertions.*

class {cls}IntegrationTest {{

    @Test
    fun endToEndFlow() {{
        val svc = {cls}()
        repeat(3) {{ i -> assertTrue(svc.process("rec-$i")) }}
        assertEquals(3, svc.count())
    }}
}}
'''
        else:  # kotest
            src = f'''package {pkg}

import io.kotest.core.spec.style.StringSpec
import io.kotest.matchers.shouldBe

class {cls}IntegrationTest : StringSpec({{

    "end to end flow records every processed item" {{
        val svc = {cls}()
        repeat(3) {{ i -> svc.process("rec-$i") shouldBe true }}
        svc.count() shouldBe 3
    }}
}})
'''
        return [Artifact(path=f"src/test/kotlin/{self._pkg_path(spec)}/{cls}IntegrationTest.kt", content=src, kind="test", language="kotlin")]

    def build_manifest(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        project = pkg_name(spec).replace("_", "-")
        if framework.id == "junit5":
            test_deps = '    testImplementation("org.junit.jupiter:junit-jupiter:5.10.2")'
        else:  # kotest
            test_deps = (
                '    testImplementation("io.kotest:kotest-runner-junit5:5.9.1")\n'
                '    testImplementation("io.kotest:kotest-assertions-core:5.9.1")'
            )
        gradle = f'''plugins {{
    kotlin("jvm") version "1.9.24"
}}

group = "{_GROUP}"
version = "0.1.0"

repositories {{
    mavenCentral()
}}

dependencies {{
{test_deps}
}}

tasks.test {{
    useJUnitPlatform()
}}

kotlin {{
    jvmToolchain(17)
}}
'''
        settings = f'rootProject.name = "{project}"\n'
        return [
            Artifact(path="build.gradle.kts", content=gradle, kind="code", language="kotlin"),
            Artifact(path="settings.gradle.kts", content=settings, kind="code", language="kotlin"),
        ]

    def component_design(self, spec: ProjectSpec, framework: TestFramework) -> str:
        cls = core_class(spec)
        pkg = self._pkg(spec)
        ops = ", ".join(f"`{o}`" for o in self._ops(spec))
        return f'''# Component Design
## {spec.title}

*Target language: **Kotlin** · unit tests: **{framework.display}**.*

## Gradle Layout
```
build.gradle.kts, settings.gradle.kts
src/main/kotlin/{self._pkg_path(spec)}/{cls}.kt
src/test/kotlin/{self._pkg_path(spec)}/{cls}Test.kt              # unit tests
src/test/kotlin/{self._pkg_path(spec)}/{cls}IntegrationTest.kt   # integration tests
```

## Public Interface: `{pkg}.{cls}`
- `validate(name: String): List<String>` — validation errors (empty = valid).
- `process(name: String): Boolean` — validate then record a `process` operation.
- `record(operation: String)` — append to the audit log.
- `count(): Int` — number of recorded operations.
- Domain operations: {ops}.

## Build & Test
```
gradle test
```
'''
