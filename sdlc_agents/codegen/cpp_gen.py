"""C++ code generator — CMake project with GoogleTest (default) or Catch2."""

from __future__ import annotations

from typing import List

from ..analysis import ProjectSpec
from ..languages import TestFramework
from ..types import Artifact
from .base import CodeGenerator, camel, core_class, operation_idents, pkg_name


class CppGenerator(CodeGenerator):
    language_id = "cpp"

    def _ns(self, spec: ProjectSpec) -> str:
        return pkg_name(spec)

    def _ops(self, spec: ProjectSpec) -> List[str]:
        return [camel(o) for o in operation_idents(spec)]

    def source_files(self, spec: ProjectSpec) -> List[Artifact]:
        ns = self._ns(spec)
        cls = core_class(spec)
        ops = self._ops(spec)
        op_decls = "\n".join(f"    bool {op}(const std::string& name);" for op in ops)
        op_defs = "\n\n".join(
            f'''bool {cls}::{op}(const std::string& name) {{
    if (!validate(name).empty()) {{
        return false;
    }}
    record("{op}");
    return true;
}}'''
            for op in ops
        )
        header = f'''// Core API for {spec.title} (auto-generated by SDLC Agents).
#pragma once

#include <cstddef>
#include <string>
#include <vector>

namespace {ns} {{

// Business logic for {spec.title}. Deterministic, dependency-light, offline.
class {cls} {{
 public:
    // Validation errors for an input name (empty vector = valid).
    std::vector<std::string> validate(const std::string& name) const;

    // Append an operation to the audit log.
    void record(const std::string& operation);

    // Validate then record a 'process' operation. Returns true on success.
    bool process(const std::string& name);
{op_decls}

    // Number of recorded operations.
    std::size_t count() const;

 private:
    std::vector<std::string> audit_;
}};

}}  // namespace {ns}
'''
        source = f'''// Core implementation for {spec.title} (auto-generated by SDLC Agents).
#include "{ns}/core.hpp"

#include <algorithm>
#include <cctype>

namespace {ns} {{

namespace {{
bool is_blank(const std::string& s) {{
    return std::all_of(s.begin(), s.end(),
                       [](unsigned char c) {{ return std::isspace(c) != 0; }});
}}
}}  // namespace

std::vector<std::string> {cls}::validate(const std::string& name) const {{
    std::vector<std::string> errors;
    if (is_blank(name)) {{
        errors.push_back("name must not be empty");
    }}
    return errors;
}}

void {cls}::record(const std::string& operation) {{
    audit_.push_back(operation);
}}

bool {cls}::process(const std::string& name) {{
    if (!validate(name).empty()) {{
        return false;
    }}
    record("process");
    return true;
}}

{op_defs}

std::size_t {cls}::count() const {{
    return audit_.size();
}}

}}  // namespace {ns}
'''
        return [
            Artifact(path=f"include/{ns}/core.hpp", content=header, kind="code", language="cpp"),
            Artifact(path="src/core.cpp", content=source, kind="code", language="cpp"),
        ]

    def unit_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        ns = self._ns(spec)
        cls = core_class(spec)
        first = self._ops(spec)[0]
        if framework.id == "catch2":
            content = f'''// Unit tests for {spec.title} (auto-generated, Catch2).
#include <catch2/catch_test_macros.hpp>

#include "{ns}/core.hpp"

TEST_CASE("validate rejects empty input", "[{ns}]") {{
    REQUIRE_FALSE({ns}::{cls}().validate("  ").empty());
}}

TEST_CASE("validate accepts non-empty input", "[{ns}]") {{
    REQUIRE({ns}::{cls}().validate("order-1").empty());
}}

TEST_CASE("process increments the operation count", "[{ns}]") {{
    {ns}::{cls} svc;
    REQUIRE(svc.process("order-1"));
    REQUIRE(svc.count() == 1u);
}}

TEST_CASE("process rejects invalid input", "[{ns}]") {{
    {ns}::{cls} svc;
    REQUIRE_FALSE(svc.process(""));
    REQUIRE(svc.count() == 0u);
}}

TEST_CASE("domain operation increments the count", "[{ns}]") {{
    {ns}::{cls} svc;
    REQUIRE(svc.{first}("order-1"));
    REQUIRE(svc.count() == 1u);
}}
'''
        else:  # gtest
            content = f'''// Unit tests for {spec.title} (auto-generated, GoogleTest).
#include <gtest/gtest.h>

#include "{ns}/core.hpp"

TEST({cls}Test, ValidateRejectsEmpty) {{
    EXPECT_FALSE({ns}::{cls}().validate("  ").empty());
}}

TEST({cls}Test, ValidateAcceptsNonEmpty) {{
    EXPECT_TRUE({ns}::{cls}().validate("order-1").empty());
}}

TEST({cls}Test, ProcessIncrementsCount) {{
    {ns}::{cls} svc;
    EXPECT_TRUE(svc.process("order-1"));
    EXPECT_EQ(svc.count(), 1u);
}}

TEST({cls}Test, ProcessRejectsInvalid) {{
    {ns}::{cls} svc;
    EXPECT_FALSE(svc.process(""));
    EXPECT_EQ(svc.count(), 0u);
}}

TEST({cls}Test, OperationIncrementsCount) {{
    {ns}::{cls} svc;
    EXPECT_TRUE(svc.{first}("order-1"));
    EXPECT_EQ(svc.count(), 1u);
}}
'''
        return [Artifact(path="tests/test_core.cpp", content=content, kind="test", language="cpp")]

    def integration_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        ns = self._ns(spec)
        cls = core_class(spec)
        if framework.id == "catch2":
            content = f'''// Integration tests for {spec.title} (auto-generated, Catch2).
#include <catch2/catch_test_macros.hpp>

#include <string>

#include "{ns}/core.hpp"

TEST_CASE("end to end flow records every processed item", "[{ns}][integration]") {{
    {ns}::{cls} svc;
    for (int i = 0; i < 3; ++i) {{
        REQUIRE(svc.process("rec-" + std::to_string(i)));
    }}
    REQUIRE(svc.count() == 3u);
}}
'''
        else:  # gtest
            content = f'''// Integration tests for {spec.title} (auto-generated, GoogleTest).
#include <gtest/gtest.h>

#include <string>

#include "{ns}/core.hpp"

TEST({cls}Integration, EndToEndFlow) {{
    {ns}::{cls} svc;
    for (int i = 0; i < 3; ++i) {{
        EXPECT_TRUE(svc.process("rec-" + std::to_string(i)));
    }}
    EXPECT_EQ(svc.count(), 3u);
}}
'''
        return [Artifact(path="tests/test_integration.cpp", content=content, kind="test", language="cpp")]

    def build_manifest(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        ns = self._ns(spec)
        project = ns.replace("_", "-")
        if framework.id == "catch2":
            fetch = '''FetchContent_Declare(
  Catch2
  URL https://github.com/catchorg/Catch2/archive/refs/tags/v3.5.4.zip
)
FetchContent_MakeAvailable(Catch2)'''
            link = "Catch2::Catch2WithMain"
            discover = '''list(APPEND CMAKE_MODULE_PATH ${catch2_SOURCE_DIR}/extras)
include(Catch)
catch_discover_tests(core_tests)'''
        else:  # gtest
            fetch = '''FetchContent_Declare(
  googletest
  URL https://github.com/google/googletest/archive/refs/tags/v1.14.0.zip
)
FetchContent_MakeAvailable(googletest)'''
            link = "GTest::gtest_main"
            discover = '''include(GoogleTest)
gtest_discover_tests(core_tests)'''
        content = f'''cmake_minimum_required(VERSION 3.14)
project({project} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

add_library(core src/core.cpp)
target_include_directories(core PUBLIC include)

enable_testing()

include(FetchContent)
{fetch}

add_executable(core_tests tests/test_core.cpp tests/test_integration.cpp)
target_link_libraries(core_tests PRIVATE core {link})
target_include_directories(core_tests PRIVATE include)

{discover}
'''
        return [Artifact(path="CMakeLists.txt", content=content, kind="code", language="cmake")]

    def component_design(self, spec: ProjectSpec, framework: TestFramework) -> str:
        ns = self._ns(spec)
        cls = core_class(spec)
        ops = ", ".join(f"`{o}`" for o in self._ops(spec))
        return f'''# Component Design
## {spec.title}

*Target language: **C++** · unit tests: **{framework.display}**.*

## CMake Layout
```
CMakeLists.txt
include/{ns}/core.hpp   # {cls} declaration
src/core.cpp            # implementation
tests/test_core.cpp         # unit tests
tests/test_integration.cpp  # integration tests
```

## Public Interface: `{ns}::{cls}`
- `std::vector<std::string> validate(const std::string& name) const` — errors (empty = valid).
- `bool process(const std::string& name)` — validate then record a `process` operation.
- `void record(const std::string& operation)` — append to the audit log.
- `std::size_t count() const` — number of recorded operations.
- Domain operations: {ops}.

## Build & Test
```
cmake -B build
cmake --build build
ctest --test-dir build
```
'''
