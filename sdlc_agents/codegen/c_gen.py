"""C code generator — CMake project with GoogleTest unit tests.

GoogleTest is a C++ harness; the C core is exposed through a header included
with ``extern "C"`` from the test translation unit (the conventional way to unit
test C with gtest).
"""

from __future__ import annotations

from typing import List

from ..analysis import ProjectSpec
from ..languages import TestFramework
from ..types import Artifact
from .base import CodeGenerator, pkg_name


class CGenerator(CodeGenerator):
    language_id = "c"

    def _prefix(self, spec: ProjectSpec) -> str:
        return pkg_name(spec)

    def source_files(self, spec: ProjectSpec) -> List[Artifact]:
        p = self._prefix(spec)
        guard = p.upper() + "_CORE_H"
        header = f'''/* Core API for {spec.title} (auto-generated by SDLC Agents). */
#ifndef {guard}
#define {guard}

#include <stddef.h>

typedef struct {{
    size_t count;
}} {p}_service;

/* Initialise a service to an empty state. */
void {p}_service_init({p}_service *svc);

/* Return 1 when the name is valid (non-blank), 0 otherwise. */
int {p}_validate(const char *name);

/* Validate then record a 'process' operation. Returns 1 on success. */
int {p}_process({p}_service *svc, const char *name);

/* Number of recorded operations. */
size_t {p}_count(const {p}_service *svc);

#endif /* {guard} */
'''
        source = f'''/* Core implementation for {spec.title} (auto-generated by SDLC Agents).
 * Deterministic, dependency-light and fully offline.
 */
#include "{p}_core.h"

#include <ctype.h>
#include <stddef.h>

static int is_blank(const char *s) {{
    if (s == NULL) {{
        return 1;
    }}
    for (; *s != '\\0'; ++s) {{
        if (!isspace((unsigned char)*s)) {{
            return 0;
        }}
    }}
    return 1;
}}

void {p}_service_init({p}_service *svc) {{
    if (svc != NULL) {{
        svc->count = 0;
    }}
}}

int {p}_validate(const char *name) {{
    return is_blank(name) ? 0 : 1;
}}

int {p}_process({p}_service *svc, const char *name) {{
    if (svc == NULL || !{p}_validate(name)) {{
        return 0;
    }}
    svc->count += 1;
    return 1;
}}

size_t {p}_count(const {p}_service *svc) {{
    return (svc != NULL) ? svc->count : 0;
}}
'''
        return [
            Artifact(path=f"include/{p}_core.h", content=header, kind="code", language="c"),
            Artifact(path=f"src/{p}_core.c", content=source, kind="code", language="c"),
        ]

    def unit_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        p = self._prefix(spec)
        content = f'''// Unit tests for {spec.title} (auto-generated, GoogleTest).
#include <gtest/gtest.h>

extern "C" {{
#include "{p}_core.h"
}}

TEST({p}_service_test, ValidateRejectsEmpty) {{
    EXPECT_EQ({p}_validate("  "), 0);
    EXPECT_EQ({p}_validate(""), 0);
}}

TEST({p}_service_test, ValidateAcceptsNonEmpty) {{
    EXPECT_EQ({p}_validate("order-1"), 1);
}}

TEST({p}_service_test, ProcessIncrementsCount) {{
    {p}_service svc;
    {p}_service_init(&svc);
    EXPECT_EQ({p}_process(&svc, "order-1"), 1);
    EXPECT_EQ({p}_count(&svc), 1u);
}}

TEST({p}_service_test, ProcessRejectsInvalid) {{
    {p}_service svc;
    {p}_service_init(&svc);
    EXPECT_EQ({p}_process(&svc, ""), 0);
    EXPECT_EQ({p}_count(&svc), 0u);
}}
'''
        return [Artifact(path=f"tests/test_{p}_core.cpp", content=content, kind="test", language="cpp")]

    def integration_tests(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        p = self._prefix(spec)
        content = f'''// Integration tests for {spec.title} (auto-generated, GoogleTest).
#include <gtest/gtest.h>
#include <string>

extern "C" {{
#include "{p}_core.h"
}}

TEST({p}_integration, EndToEndFlow) {{
    {p}_service svc;
    {p}_service_init(&svc);
    for (int i = 0; i < 3; ++i) {{
        std::string name = "rec-" + std::to_string(i);
        EXPECT_EQ({p}_process(&svc, name.c_str()), 1);
    }}
    EXPECT_EQ({p}_count(&svc), 3u);
}}
'''
        return [Artifact(path=f"tests/test_{p}_integration.cpp", content=content, kind="test", language="cpp")]

    def build_manifest(self, spec: ProjectSpec, framework: TestFramework) -> List[Artifact]:
        p = self._prefix(spec)
        project = p.replace("_", "-")
        content = f'''cmake_minimum_required(VERSION 3.14)
project({project} LANGUAGES C CXX)

set(CMAKE_C_STANDARD 11)
set(CMAKE_CXX_STANDARD 17)

add_library({p}_core src/{p}_core.c)
target_include_directories({p}_core PUBLIC include)

enable_testing()

include(FetchContent)
FetchContent_Declare(
  googletest
  URL https://github.com/google/googletest/archive/refs/tags/v1.14.0.zip
)
FetchContent_MakeAvailable(googletest)

add_executable(
  {p}_tests
  tests/test_{p}_core.cpp
  tests/test_{p}_integration.cpp
)
target_link_libraries({p}_tests PRIVATE {p}_core GTest::gtest_main)
target_include_directories({p}_tests PRIVATE include)

include(GoogleTest)
gtest_discover_tests({p}_tests)
'''
        return [Artifact(path="CMakeLists.txt", content=content, kind="code", language="cmake")]

    def component_design(self, spec: ProjectSpec, framework: TestFramework) -> str:
        p = self._prefix(spec)
        return f'''# Component Design
## {spec.title}

*Target language: **C** · unit tests: **{framework.display}**.*

## CMake Layout
```
CMakeLists.txt
include/{p}_core.h    # public C API
src/{p}_core.c        # implementation
tests/test_{p}_core.cpp         # unit tests (GoogleTest, extern "C")
tests/test_{p}_integration.cpp  # integration tests
```

## Public API (`{p}_core.h`)
- `void {p}_service_init({p}_service *svc)` — initialise to empty state.
- `int {p}_validate(const char *name)` — 1 if valid (non-blank), else 0.
- `int {p}_process({p}_service *svc, const char *name)` — validate then record.
- `size_t {p}_count(const {p}_service *svc)` — number of recorded operations.

## Build & Test
```
cmake -B build
cmake --build build
ctest --test-dir build
```
'''
